create table if not exists public.control_test_jump_trials (
  id bigint generated by default as identity primary key,
  measurement_id bigint not null references public.control_test_measurements(id) on delete cascade,
  scan_id uuid not null references public.control_test_scans(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  test_code text not null check (test_code in ('vertical_jump','drop_jump')),
  trial_number smallint not null check (trial_number between 1 and 3),
  drop_height_cm numeric check (drop_height_cm is null or drop_height_cm > 0),
  jump_height_cm numeric not null check (jump_height_cm > 0),
  contact_time_ms numeric check (contact_time_ms is null or contact_time_ms > 0),
  rsi numeric check (rsi is null or rsi > 0),
  is_valid boolean not null default true,
  invalid_reason text,
  equipment text,
  protocol_version integer not null default 2,
  measured_at timestamptz not null default now(),
  raw_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(measurement_id,trial_number)
);
create index if not exists control_test_jump_trials_scan_test_idx on public.control_test_jump_trials(scan_id,test_code,trial_number);
alter table public.control_test_jump_trials enable row level security;
drop policy if exists "Athletes and assigned coaches read jump trials" on public.control_test_jump_trials;
create policy "Athletes and assigned coaches read jump trials" on public.control_test_jump_trials for select to authenticated
using (user_id=(select auth.uid()) or public.is_assigned_coach(user_id));
drop policy if exists "Athletes create jump trials" on public.control_test_jump_trials;
create policy "Athletes create jump trials" on public.control_test_jump_trials for insert to authenticated
with check (user_id=(select auth.uid()) and exists(select 1 from public.control_test_measurements m where m.id=measurement_id and m.scan_id=scan_id and m.user_id=(select auth.uid())));
drop policy if exists "Athletes update jump trials" on public.control_test_jump_trials;
create policy "Athletes update jump trials" on public.control_test_jump_trials for update to authenticated
using (user_id=(select auth.uid())) with check (user_id=(select auth.uid()));
drop policy if exists "Athletes delete jump trials" on public.control_test_jump_trials;
create policy "Athletes delete jump trials" on public.control_test_jump_trials for delete to authenticated using (user_id=(select auth.uid()));

