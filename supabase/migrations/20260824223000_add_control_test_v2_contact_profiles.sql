-- VAULTEX CONTROL TEST Ver.2 / CONTACT PROFILE Ver.1 BETA.
-- Historical scans remain untouched: version columns are intentionally nullable.

alter table public.control_test_scans
  add column if not exists control_test_version text,
  add column if not exists protocol_version integer,
  add column if not exists contact_profile_version text,
  add column if not exists contact_profile_code text,
  add column if not exists contact_profile_snapshot jsonb;

alter table public.control_test_scans
  drop constraint if exists control_test_scans_contact_profile_code_check,
  add constraint control_test_scans_contact_profile_code_check
    check (contact_profile_code is null or contact_profile_code in ('QUICK','BALANCED','FORCE','NOT_MEASURED'));

comment on column public.control_test_scans.control_test_version is 'CONTROL TEST version used when the scan was measured. NULL means legacy.';
comment on column public.control_test_scans.contact_profile_snapshot is 'Immutable CONTACT PROFILE result and thresholds used for this scan.';

create table if not exists public.contact_profile_settings (
  version text primary key,
  quick_upper_ms integer not null check (quick_upper_ms > 0),
  balanced_upper_ms integer not null check (balanced_upper_ms > quick_upper_ms),
  junior_drop_height_cm numeric not null check (junior_drop_height_cm > 0),
  youth_drop_height_cm numeric not null check (youth_drop_height_cm > 0),
  elite_drop_height_cm numeric not null check (elite_drop_height_cm > 0),
  masters_drop_height_cm numeric not null check (masters_drop_height_cm > 0),
  status text not null default 'beta' check (status in ('draft','beta','active','retired')),
  is_current boolean not null default false,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists contact_profile_one_current_idx on public.contact_profile_settings(is_current) where is_current;
alter table public.contact_profile_settings enable row level security;
drop policy if exists "Authenticated users read contact profile settings" on public.contact_profile_settings;
create policy "Authenticated users read contact profile settings" on public.contact_profile_settings for select to authenticated using (true);
drop policy if exists "Admins manage contact profile settings" on public.contact_profile_settings;
create policy "Admins manage contact profile settings" on public.contact_profile_settings for all to authenticated
using (exists(select 1 from public.user_roles r where r.user_id=(select auth.uid()) and r.role='admin'))
with check (exists(select 1 from public.user_roles r where r.user_id=(select auth.uid()) and r.role='admin'));

